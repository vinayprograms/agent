func TestWrite(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "nested")
	o := Options{Provider: ProviderOpenAI, Model: "gpt-4o", Workspace: "."}

	written, err := Write(dir, o, false)
	if err != nil {
		t.Fatalf("Write: %v", err)
	}
	want := []string{filepath.Join(dir, "agent.toml"), filepath.Join(dir, "policy.toml")}
	if !slices.Equal(written, want) {
		t.Errorf("written = %v, want %v", written, want)
	}
	for _, p := range written {
		info, err := os.Stat(p)
		if err != nil {
			t.Fatalf("stat %s: %v", p, err)
		}
		if info.Mode().Perm() != fileMode {
			t.Errorf("%s mode = %v, want %v", p, info.Mode().Perm(), os.FileMode(fileMode))
		}
	}

	// Without --force an existing file blocks the whole write, and every
	// blocking file is named.
	if _, err := Write(dir, o, false); err == nil {
		t.Fatal("second Write must refuse to overwrite")
	} else {
		for _, p := range want {
			if !strings.Contains(err.Error(), p) {
				t.Errorf("error must name %s: %v", p, err)
			}
		}
		if !strings.Contains(err.Error(), "--force") {
			t.Errorf("error must suggest --force: %v", err)
		}
	}

	o.Model = "gpt-5"
	if _, err := Write(dir, o, true); err != nil {
		t.Fatalf("forced Write: %v", err)
	}
	body, err := os.ReadFile(want[0])
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(body), "gpt-5") {
		t.Error("forced Write must overwrite")
	}
}

func TestWrite_Errors(t *testing.T) {
	root := t.TempDir()

	// A file where the directory should be: MkdirAll fails.
	blocked := filepath.Join(root, "notadir")
	if err := os.WriteFile(blocked, nil, 0644); err != nil {
		t.Fatal(err)
	}
	if _, err := Write(filepath.Join(blocked, "sub"), Options{}, false); err == nil {
		t.Error("Write into a non-directory must fail")
	}

	// A directory where policy.toml should be: the second file write fails
	// after the first succeeded, and the partial list comes back.
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "policy.toml"), 0755); err != nil {
		t.Fatal(err)
	}
	written, err := Write(dir, Options{}, true)
	if err == nil {
		t.Fatal("blocked policy.toml must surface an error")
	}
	if !slices.Equal(written, []string{filepath.Join(dir, "agent.toml")}) {
		t.Errorf("partial write list = %v", written)
	}
}
