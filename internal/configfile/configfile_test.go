// TestPolicyTOML_ParsesWithNoUnknownKeys is the contract that matters: every
// generated policy must load cleanly under the current policy schema.
func TestPolicyTOML_ParsesWithNoUnknownKeys(t *testing.T) {
	for _, o := range []Options{
		full(),
		{DefaultDeny: false, AllowBash: true, AllowWeb: true},
		{DefaultDeny: false, AllowBash: false, AllowWeb: false},
		{DefaultDeny: true, AllowBash: false, AllowWeb: false},
		{DefaultDeny: true, EnableMCP: true},
	} {
		content := PolicyTOML(o)
		pol, unknown, err := policy.FromTOMLWithUnknownKeys(content, "/work", "")
		if err != nil {
			t.Fatalf("parse %+v: %v\n%s", o, err, content)
		}
		if len(unknown) > 0 {
			t.Errorf("unknown keys %v for %+v:\n%s", unknown, o, content)
		}
		if pol.DefaultDeny != o.DefaultDeny {
			t.Errorf("default_deny = %v, want %v", pol.DefaultDeny, o.DefaultDeny)
		}
	}
}

func TestPolicyTOML_ToolSections(t *testing.T) {
	tests := []struct {
		name    string
		opts    Options
		want    []string
		notWant []string
	}{
		{
			name: "restrictive bash gets a deny list",
			opts: Options{DefaultDeny: true, AllowBash: true, AllowWeb: true},
			want: []string{"[tools.bash]", `deny = ["rm -rf *"`, "[tools.web_fetch]", "# allow = [\"github.com\""},
		},
		{
			name:    "permissive bash gets a recommendation comment",
			opts:    Options{DefaultDeny: false, AllowBash: true, AllowWeb: true},
			want:    []string{"[tools.bash]", "# Recommended for security:"},
			notWant: []string{`deny = ["rm -rf *"`},
		},
		{
			name:    "permissive without bash explains why it cannot be disabled",
			opts:    Options{DefaultDeny: false},
			want:    []string{"bash cannot be disabled individually", "web_search/web_fetch cannot be disabled individually"},
			notWant: []string{"[tools.bash]", "[tools.web_search]"},
		},
		{
			name:    "restrictive without bash simply omits it",
			opts:    Options{DefaultDeny: true},
			notWant: []string{"[tools.bash]", "[tools.web_search]", "cannot be disabled"},
		},
		{
			name: "mcp servers become allow patterns in sorted order",
			opts: Options{EnableMCP: true, MCPServers: map[string]MCPServerSetup{"zeta": {}, "alpha": {}}},
			want: []string{"[mcp]\nenabled = true\n", `allow = ["alpha:*", "zeta:*"]`},
		},
		{
			name: "mcp without servers keeps a commented example",
			opts: Options{EnableMCP: true},
			want: []string{`# allow = ["memory:*", "filesystem:read_file"]`},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out := PolicyTOML(tt.opts)
			for _, w := range tt.want {
				if !strings.Contains(out, w) {
					t.Errorf("missing %q:\n%s", w, out)
				}
			}
			for _, w := range tt.notWant {
				if strings.Contains(out, w) {
					t.Errorf("unexpected %q:\n%s", w, out)
				}
			}
		})
	}
}

func TestApplyScenario(t *testing.T) {
	tests := []struct {
		scenario     string
		wantProvider string
		wantDeny     bool
		wantBash     bool
		wantMode     string
	}{
		{ScenarioLocal, ProviderOllamaLocal, false, true, "default"},
		{ScenarioDev, ProviderAnthropic, false, true, "default"},
		{ScenarioTeam, ProviderLiteLLM, true, true, "default"},
		{ScenarioProduction, ProviderLiteLLM, true, false, "paranoid"},
		{ScenarioDocker, ProviderLiteLLM, true, true, "default"},
	}
	for _, tt := range tests {
		t.Run(tt.scenario, func(t *testing.T) {
			o := Options{Scenario: tt.scenario}
			o.ApplyScenario()
			if o.Provider != tt.wantProvider || o.DefaultDeny != tt.wantDeny ||
				o.AllowBash != tt.wantBash || o.SecurityMode != tt.wantMode {
				t.Errorf("got %+v", o)
			}
		})
	}
	if o := (Options{Scenario: "nonsense", Provider: "keep"}); func() Options { o.ApplyScenario(); return o }().Provider != "keep" {
		t.Error("unknown scenario must leave Options untouched")
	}
	if !slices.Contains(Scenarios(), ScenarioProduction) || len(Scenarios()) != 5 {
		t.Errorf("Scenarios() = %v", Scenarios())
	}
	if o := (Options{Scenario: ScenarioDocker}); func() Options { o.ApplyScenario(); return o }().CredentialMethod != "env" {
		t.Error("docker scenario must select env credentials")
	}
}

func TestProviderDefaults(t *testing.T) {
	for _, p := range append(Providers(), "unknown-provider") {
		o := Options{Provider: p, SmallLLMProvider: p}
		o.SetDefaultModel()
		o.SetDefaultSmallModel()
		if p != ProviderCustom && p != "unknown-provider" && o.Model == "" {
			t.Errorf("%s: no default model", p)
		}
		if o.SmallLLMModel != o.Model && o.SmallLLMModel == "" {
			t.Errorf("%s: no default small model", p)
		}
		if NeedsBaseURL(p) && DefaultBaseURL(p) == "" && p != ProviderCustom {
			t.Errorf("%s needs a base URL but has no default", p)
		}
		if !NeedsBaseURL(p) && DefaultBaseURL(p) != "" {
			t.Errorf("%s: unexpected default base URL %q", p, DefaultBaseURL(p))
		}
	}
	// Custom is the escape hatch: it needs a base URL but cannot guess one.
	if !NeedsBaseURL(ProviderCustom) || DefaultBaseURL(ProviderCustom) != "" {
		t.Error("custom provider must need a base URL with no default")
	}
	// A small LLM on the same provider inherits the main base URL.
	o := Options{Provider: ProviderLiteLLM, BaseURL: "http://proxy/v1", SmallLLMProvider: ProviderLiteLLM}
	o.SetDefaultSmallModel()
	if o.SmallLLMBaseURL != "http://proxy/v1" {
		t.Errorf("small_llm base_url = %q", o.SmallLLMBaseURL)
	}
}

